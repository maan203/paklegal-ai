// Measures Urdu speech-to-text accuracy with the same Whisper settings the app uses
// (src/lib/ai-functions.ts: whisper-large-v3, language "ur"), and compares with auto-detect.
//
//   python scripts/speech/make-urdu-audio.py   (once, creates the test audio)
//   npm run speech:eval
//
// Writes knowledge/eval/speech-results.md.

import fs from "node:fs";
import path from "node:path";
import OpenAI, { toFile } from "openai";

const ROOT = path.resolve(import.meta.dirname, "../..");
const DIR = path.join(ROOT, "knowledge/eval/speech");
const key = fs
  .readFileSync(path.join(ROOT, ".env.local"), "utf8")
  .match(/GROQ_API_KEY=(.*)/)?.[1]
  ?.trim();
const groq = new OpenAI({ apiKey: key, baseURL: "https://api.groq.com/openai/v1" });

// Spelling variants, diacritics and punctuation are not counted as errors.
const words = (s) =>
  s
    .normalize("NFC")
    .replace(/[\u064B-\u065F\u0670]/g, "")
    .replace(/[يى]/g, "ی")
    .replace(/ك/g, "ک")
    .replace(/[هۂ]/g, "ہ")
    .replace(/[۔،؟!.,?"'()\-]/g, " ")
    .toLowerCase()
    .split(/\s+/)
    .filter(Boolean);

function wordAccuracy(ref, hyp) {
  const r = words(ref),
    h = words(hyp);
  const d = Array.from({ length: r.length + 1 }, (_, i) => [i, ...Array(h.length).fill(0)]);
  for (let j = 1; j <= h.length; j++) d[0][j] = j;
  for (let i = 1; i <= r.length; i++)
    for (let j = 1; j <= h.length; j++)
      d[i][j] = Math.min(
        d[i - 1][j] + 1,
        d[i][j - 1] + 1,
        d[i - 1][j - 1] + (r[i - 1] === h[j - 1] ? 0 : 1),
      );
  return Math.max(0, 1 - d[r.length][h.length] / r.length);
}
const scriptOf = (s) =>
  /[\u0900-\u097F]/.test(s) ? "Hindi (Devanagari)" : /[\u0600-\u06FF]/.test(s) ? "Urdu" : "Latin";

async function transcribe(file, language) {
  const res = await groq.audio.transcriptions.create({
    file: await toFile(fs.readFileSync(path.join(DIR, file)), file, { type: "audio/mpeg" }),
    model: "whisper-large-v3",
    ...(language ? { language } : {}),
  });
  return res.text.trim();
}

const manifest = JSON.parse(fs.readFileSync(path.join(DIR, "manifest.json"), "utf8"));
const rows = [];
for (const m of manifest) {
  const app = await transcribe(m.file, "ur");
  const auto = await transcribe(m.file, null);
  rows.push({
    ...m,
    app,
    auto,
    appAcc: wordAccuracy(m.text, app),
    autoAcc: wordAccuracy(m.text, auto),
  });
  console.log(
    `${m.name}: app ${Math.round(100 * wordAccuracy(m.text, app))}% (${scriptOf(app)}), auto ${Math.round(100 * wordAccuracy(m.text, auto))}% (${scriptOf(auto)})`,
  );
}
const avg = (k) => Math.round((100 * rows.reduce((s, r) => s + r[k], 0)) / rows.length);
const report = [
  "# Urdu speech-to-text evaluation",
  "",
  `Generated by \`npm run speech:eval\` on ${new Date().toISOString().slice(0, 10)}. ${rows.length} Urdu incident recordings made with Microsoft neural voices (\`scripts/speech/make-urdu-audio.py\`), transcribed with \`whisper-large-v3\` on Groq.`,
  "",
  "| Setting | Average word accuracy | Output script |",
  "|---|---|---|",
  `| Language set to Urdu (what the app does) | ${avg("appAcc")}% | ${rows.map((r) => scriptOf(r.app)).join(", ")} |`,
  `| Whisper auto-detect | ${avg("autoAcc")}% | ${rows.map((r) => scriptOf(r.auto)).join(", ")} |`,
  "",
  "Word accuracy = 1 - word error rate, ignoring diacritics, punctuation and common spelling variants.",
  "",
  "## Per recording (app setting)",
  "",
  "| Recording | Voice | Word accuracy | Transcript |",
  "|---|---|---|---|",
  ...rows.map((r) => `| ${r.name} | ${r.voice} | ${Math.round(100 * r.appAcc)}% | ${r.app} |`),
  "",
  'Synthetic voices are clearer than real speech in a noisy room, so these numbers are an upper bound. The review step exists because the errors that do happen are in exactly the words that matter (names, places, amounts, and English words mixed into Urdu such as "FIR").',
  "",
].join("\n");
fs.writeFileSync(path.join(ROOT, "knowledge/eval/speech-results.md"), report);
console.log(
  `\nAverage: app ${avg("appAcc")}% | auto-detect ${avg("autoAcc")}%\nWritten to knowledge/eval/speech-results.md`,
);
