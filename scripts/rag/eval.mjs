// Measures retrieval quality on knowledge/eval/questions.json and writes knowledge/eval/results.md.
//
//   npm run rag:eval
//
// For each legal question: is a correct provision ranked 1st (Hit@1), in the top 3 / top 5,
// and the mean reciprocal rank (MRR). For off-topic questions: is the best score below the
// relevance threshold, so the app correctly finds "no matching provision"?
// Run with and without the glossary to show what the query expansion contributes.
// Uses your `wrangler login` session through the AI and VECTORIZE bindings.

import fs from "node:fs";
import path from "node:path";
import { getPlatformProxy } from "wrangler";
import { expandQuery } from "../../src/lib/rag/glossary.ts";

const ROOT = path.resolve(import.meta.dirname, "../..");
const EMBEDDING_MODEL = "@cf/baai/bge-m3"; // must match src/lib/rag/cloudflare.ts
const MIN_SCORE = 0.5; // must match src/lib/rag/retrieve.ts
const TOP_K = 5;

const { questions } = JSON.parse(
  fs.readFileSync(path.join(ROOT, "knowledge/eval/questions.json"), "utf8"),
);
const { env, dispose } = await getPlatformProxy({
  configPath: path.join(ROOT, "wrangler.jsonc"),
  remoteBindings: true,
});

// Rank (1-based) of the first correct provision; parts of a split provision count too.
function rankOf(matches, expected) {
  const i = matches.findIndex((m) => expected.some((e) => m.id === e || m.id.startsWith(`${e}-p`)));
  return i < 0 ? null : i + 1;
}

async function run(useGlossary) {
  const texts = questions.map((q) => (useGlossary ? expandQuery(q.q) : q.q));
  const { data } = await env.AI.run(EMBEDDING_MODEL, { text: texts });
  const rows = [];
  for (const [i, q] of questions.entries()) {
    const { matches } = await env.VECTORIZE.query(data[i], { topK: TOP_K, returnMetadata: "none" });
    rows.push({
      ...q,
      rank: rankOf(matches, q.expected),
      best: matches[0]?.score ?? 0,
      top: matches.slice(0, 3),
    });
  }
  return rows;
}

function metrics(rows) {
  const legal = rows.filter((r) => r.expected.length);
  const offTopic = rows.filter((r) => !r.expected.length);
  const pct = (n, d) => (d ? `${Math.round((100 * n) / d)}%` : "-");
  const byLang = (lang) => legal.filter((r) => r.lang === lang);
  const hits = (list, k) => list.filter((r) => r.rank && r.rank <= k).length;
  return {
    n: legal.length,
    hit1: pct(hits(legal, 1), legal.length),
    hit3: pct(hits(legal, 3), legal.length),
    hit5: pct(hits(legal, 5), legal.length),
    mrr: (legal.reduce((s, r) => s + (r.rank ? 1 / r.rank : 0), 0) / legal.length).toFixed(2),
    en: `${pct(hits(byLang("en"), 3), byLang("en").length)} (${byLang("en").length})`,
    ur: `${pct(hits(byLang("ur"), 3), byLang("ur").length)} (${byLang("ur").length})`,
    offTopic: `${pct(offTopic.filter((r) => r.best < MIN_SCORE).length, offTopic.length)} (${offTopic.length})`,
    legalAboveThreshold: pct(legal.filter((r) => r.best >= MIN_SCORE).length, legal.length),
  };
}

try {
  const withGlossary = await run(true);
  const withoutGlossary = await run(false);
  const a = metrics(withGlossary);
  const b = metrics(withoutGlossary);

  const table = [
    "| Metric | With glossary | Without glossary |",
    "|---|---|---|",
    `| Hit@1 (correct provision ranked first) | ${a.hit1} | ${b.hit1} |`,
    `| Hit@3 | ${a.hit3} | ${b.hit3} |`,
    `| Hit@5 | ${a.hit5} | ${b.hit5} |`,
    `| MRR | ${a.mrr} | ${b.mrr} |`,
    `| Hit@3, English questions | ${a.en} | ${b.en} |`,
    `| Hit@3, Urdu questions | ${a.ur} | ${b.ur} |`,
    `| Legal questions scoring above the ${MIN_SCORE} threshold | ${a.legalAboveThreshold} | ${b.legalAboveThreshold} |`,
    `| Off-topic questions correctly rejected | ${a.offTopic} | ${b.offTopic} |`,
  ].join("\n");

  const misses = withGlossary
    .filter((r) => r.expected.length && (!r.rank || r.rank > 1))
    .map(
      (r) =>
        `| ${r.q} | ${r.expected.join(", ")} | ${r.rank ?? "not in top 5"} | ${r.top.map((m) => `${m.id} (${m.score.toFixed(2)})`).join(", ")} |`,
    );

  const report = [
    "# Retrieval evaluation",
    "",
    `Generated by \`npm run rag:eval\` on ${new Date().toISOString().slice(0, 10)}. ${a.n} legal questions (English and Urdu) and ${questions.length - a.n} off-topic questions from \`knowledge/eval/questions.json\`, searched against the live index (${EMBEDDING_MODEL}, top ${TOP_K}).`,
    "",
    table,
    "",
    "## Questions where the expected provision was not ranked first (with glossary)",
    "",
    misses.length
      ? ["| Question | Expected | Rank | Top 3 returned |", "|---|---|---|---|", ...misses].join(
          "\n",
        )
      : "None.",
    "",
  ].join("\n");
  fs.writeFileSync(path.join(ROOT, "knowledge/eval/results.md"), report);
  console.log(`${table}\n\nWritten to knowledge/eval/results.md`);
} finally {
  await dispose();
}
